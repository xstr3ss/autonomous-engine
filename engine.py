TESTS_LOCKED = "Do NOT edit the test files. Fix the source code only."
TESTS_UNLOCKED = (
    "The tests are still failing after a fix attempt, so a test itself may be wrong (bad expectation or setup). "
    "If a test is wrong, output the COMPLETE corrected test file with FILE:; otherwise fix the source code."
)

GENERATED_MARKER = "# Generated by Fable TDD loop"


# --------------------------------------------------------------------------- #
# Engine Orchestrator
# --------------------------------------------------------------------------- #
class SelfHealingEngine:
    def __init__(self, config: Optional[Config] = None):
        self.cfg = config or Config()
        self.workspace = self.cfg.workspace.resolve()
        
        # Modular Clients
        self.llm = LLMClient(self.cfg)
        
        self._pytest_ok: Optional[bool] = None
        self.last_tdd_report: Optional[TddReport] = None

    # ---- Safe filesystem helpers ----------------------------------------- #
    def _safe_path(self, name: str) -> Path:
        path = (self.workspace / name).resolve()
        if path != self.workspace and self.workspace not in path.parents:
            raise ValueError(f"path escapes workspace: {name}")
        return path

    @staticmethod
    def _atomic_write(path: Path, content: str) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".fable-", suffix=".tmp")
        try:
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as f:
                f.write(content)
            os.replace(tmp, path)
        except BaseException:
            if os.path.exists(tmp):
                os.unlink(tmp)
            raise

    def _rel(self, path: Path) -> str:
        try:
            return path.resolve().relative_to(self.workspace).as_posix()
        except ValueError:
            return str(path)

    # ---- Actions ---------------------------------------------------------- #
    def execute_bash(self, response_text: str) -> bool:
        for cmd in DiffEngine.parse_bash_blocks(response_text):
            cmd = cmd.strip()
            if not cmd:
                continue
            if BLOCKED_COMMANDS.search(cmd):
                log.error("⛔ [Fable Bash] Blocked unsafe command: %s", cmd)
                return False
            if self.cfg.confirm_bash and input(f"Run `{cmd}`? [y/N] ").strip().lower() != "y":
                log.info("⏭️ [Fable Bash] Skipped: %s", cmd)
                continue

            log.info("⚡ [Fable Bash] Executing: %s", cmd)
            try:
                result = subprocess.run(
                    cmd, shell=True, capture_output=True, text=True,
                    cwd=self.workspace, timeout=self.cfg.bash_timeout,
                )
            except subprocess.TimeoutExpired:
                log.error("❌ [Fable Bash] Timed out after %ss: %s", self.cfg.bash_timeout, cmd)
                return False
            except Exception as e:
                log.error("❌ [Fable Bash] System Error: %s", e)
                return False

            if result.returncode == 0:
                log.info("✅ [Fable Bash] Success:\n%s", result.stdout.strip())
            else:
                log.error("❌ [Fable Bash] Error:\n%s", result.stderr.strip())
                return False
        return True

    def apply_code_edits(
        self,
        response_text: str,
        accept: Optional[Callable[[Path], bool]] = None,
        legacy: bool = True,
        overwrite_fallback: bool = False,
    ) -> list[Path]:
        changed: list[Path] = []
        blocks = parse_file_blocks(response_text)

        if not blocks:
            legacy_file = self.workspace / "strategy.py"
            if legacy and legacy_file.exists():
                ok, _ = DiffEngine.patch_file(str(legacy_file), response_text)
                if ok:
                    log.info("✅ [Engine] Updated strategy.py via AST")
                    changed.append(legacy_file)
            return changed

        for name, body in blocks:
            try:
                target = self._safe_path(name)
            except ValueError as e:
                log.error("⛔ [Engine] %s", e)
                continue
            if accept is not None and not accept(target):
                log.debug("[Engine] Ignoring %s (not allowed in this step)", name)
                continue

            if target.exists():
                code = extract_code(body)
                if overwrite_fallback and self._is_full_rewrite(target, code):
                    self._atomic_write(target, code)
                    log.info("✅ [Engine] Rewrote %s (complete file supplied)", name)
                    changed.append(target)
                    continue
                ok, msg = DiffEngine.patch_file(str(target), body)
                if ok:
                    log.info("✅ [Engine] Updated %s via AST Splicing", name)
                    changed.append(target)
                elif overwrite_fallback and target.suffix == ".py":
                    if "<<<<<<<" not in code and self._parses(code):
                        self._atomic_write(target, code)
                        log.info("✅ [Engine] Rewrote %s (could not patch: %s)", name, msg)
                        changed.append(target)
                    else:
                        log.warning("⚠️ [Engine] Could not update %s: %s", name, msg)
                else:
                    log.warning("⚠️ [Engine] Could not splice %s: %s", name, msg)
            else:
                self._atomic_write(target, extract_code(body))
                log.info("✅ [Engine] Created and wrote to %s", name)
                changed.append(target)
        return changed

    @staticmethod
    def _parses(code: str) -> bool:
        try:
            ast.parse(code)
            return True
        except (SyntaxError, ValueError):
            return False

    @staticmethod
    def _top_level_defs(code: str) -> set[str]:
        return {n.name for n in ast.parse(code).body
                if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef))}

    def _is_full_rewrite(self, target: Path, code: str) -> bool:
        if target.suffix != ".py" or "<<<<<<<" in code:
            return False
        try:
            new_defs = self._top_level_defs(code)
            old_defs = self._top_level_defs(target.read_text(encoding="utf-8"))
        except (SyntaxError, ValueError, OSError, UnicodeDecodeError):
            return False
        return bool(old_defs) and old_defs <= new_defs

    def _git_commit(self, files: list[Path], message: str = "Fable Auto-Commit: Task completed") -> None:
        def git(*args: str) -> subprocess.CompletedProcess:
            return subprocess.run(["git", *args], cwd=self.workspace, capture_output=True, text=True)

        try:
            if git("rev-parse", "--is-inside-work-tree").returncode != 0:
                return
            rel = sorted({str(p.relative_to(self.workspace)) for p in files if p.exists()})
            if not rel or git("add", "--", *rel).returncode != 0:
                return
            if git("diff", "--cached", "--quiet").returncode == 0:
                return
            if git("commit", "-m", message).returncode == 0:
                log.info("📝 [Git] AI successfully committed changes.")
        except FileNotFoundError:
            log.debug("git not installed; skipping commit")

    # ---- Test-driven loop ------------------------------------------------- #
    def _is_test_path(self, path: Path) -> bool:
        try:
            parts = path.resolve().relative_to(self.workspace).parts
        except ValueError:
            return False
        return (
            (bool(parts) and parts[0] == self.cfg.tests_dir)
            or path.name.startswith("test_")
            or path.name.endswith("_test.py")
            or path.name == "conftest.py"
        )

    def _tdd_sources(self, changed: list[Path]) -> list[Path]:
        out: list[Path] = []
        for p in changed:
            if p in out or p.suffix != ".py" or self._is_test_path(p) or p.name in ("setup.py", "__init__.py"):
                continue
            try:
                if not p.read_text(encoding="utf-8").strip():
                    continue
            except (OSError, UnicodeDecodeError):
                continue
            out.append(p)
        return out

    def _test_target(self, source: Path) -> Path:
        slug = "_".join(source.resolve().relative_to(self.workspace).with_suffix("").parts)
        tests = self.workspace / self.cfg.tests_dir
        target = tests / f"test_{slug}.py"
        if target.exists():
            try:
                generated = GENERATED_MARKER in target.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                generated = False
            if not generated:
                target = tests / f"test_{slug}_fable.py"
        return target

    def _render_files(self, paths: list[Path], budget: int) -> str:
        parts, per_file = [], max(budget // max(len(paths), 1), 1000)
        for p in paths:
            try:
                text = p.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            parts.append(f"### {self._rel(p)}\n```python\n{clip_text(text, per_file)}\n```")
        return "\n\n".join(parts)

    def _has_pytest(self) -> bool:
        return subprocess.run([sys.executable, "-c", "import pytest"], capture_output=True).returncode == 0

    def _ensure_pytest(self) -> bool:
        if self._pytest_ok is None:
            self._pytest_ok = self._has_pytest()
            if not self._pytest_ok and self.cfg.tdd_auto_install:
                log.info("📦 [TDD] pytest not found, installing it...")
                try:
                    r = subprocess.run(
                        [sys.executable, "-m", "pip", "install", "-q", "pytest"],
                        capture_output=True, text=True, timeout=300,
                    )
                    self._pytest_ok = r.returncode == 0 and self._has_pytest()
                except (subprocess.TimeoutExpired, OSError):
                    self._pytest_ok = False
        return self._pytest_ok

    def _run_pytest(self, test_files: list[Path]) -> PytestResult:
        cmd = [
            sys.executable, "-m", "pytest", "-q", "--tb=short", "-rfE", "--maxfail=5", "-p", "no:cacheprovider",
            *[os.path.relpath(p, self.workspace) for p in test_files],
        ]
        kwargs = dict(
            cwd=self.workspace, env=sandbox_env(self.workspace),
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
            text=True, encoding="utf-8", errors="replace",
        )
        if os.name == "posix":
            kwargs["start_new_session"] = True
            kwargs["preexec_fn"] = limit_resources(self.cfg.tdd_timeout + 10)

        log.info("🧪 [TDD] Running pytest in sandbox...")
        proc = subprocess.Popen(cmd, **kwargs)
        try:
            out, _ = proc.communicate(timeout=self.cfg.tdd_timeout)
            return PytestResult(proc.returncode, out or "")
        except subprocess.TimeoutExpired:
            try:
                if os.name == "posix":
                    os.killpg(os.getpgid(proc.pid), signal.SIGKILL)
                else:
                    proc.kill()
            except (ProcessLookupError, PermissionError):
                pass
            out, _ = proc.communicate()
            return PytestResult(124, (out or "") + f"\nTimed out after {self.cfg.tdd_timeout}s", timed_out=True)

    def _write_test_files(self, response_text: str, targets: list[Path], lenient: bool) -> tuple[list[Path], str]:
        blocks = parse_file_blocks(response_text)
        if not blocks:
            return [], "no FILE: sections found"

        wanted = {t.resolve() for t in targets}
        pairs: list[tuple[Path, str]] = []
        for name, body in blocks:
            try:
                path = self._safe_path(name)
            except ValueError:
                continue
            if path in wanted:
                pairs.append((path, body))
        if not pairs and lenient and len(targets) == 1:
            pairs = [(targets[0], blocks[0][1])]
        if not pairs:
            return [], "no FILE: section matched the requested test file paths"

        written, problems = [], []
        for path, body in pairs:
            code = extract_code(body)
            try:
                ast.parse(code)
            except SyntaxError as e:
                problems.append(f"{path.name}: syntax error on line {e.lineno}: {e.msg}")
                continue
            if "def test_" not in code:
                problems.append(f"{path.name}: contains no test_ functions")
                continue
            if GENERATED_MARKER not in code:
                code = f"{GENERATED_MARKER}\n{code}"
            self._atomic_write(path, code)
            written.append(path)
        return written, "; ".join(problems)

    def _generate_tests(self, request: str, sources: list[Path], targets: list[Path]) -> list[Path]:
        mapping = "\n".join(f"- {self._rel(t)} (tests for {self._rel(s)})" for s, t in zip(sources, targets))
        prompt = TEST_PROMPT.substitute(
            request=request, targets=mapping,
            sources=self._render_files(sources, self.cfg.tdd_context_chars),
        )
        for attempt in (1, 2):
            log.info("🧪 [TDD] Writing test suite (attempt %d/2)...", attempt)
            try:
                text = self.llm.generate(prompt, force_cloud=attempt == 2, slow=True)
            except Exception as e:
                log.error("❌ [TDD] Could not reach a model to write tests: %s", e)
                return []
            written, problem = self._write_test_files(text, targets, lenient=True)
            if written:
                for p in written:
                    log.info("✅ [TDD] Wrote %s", self._rel(p))
                return written
            log.warning("⚠️ [TDD] Test file rejected: %s", problem)
            prompt += (f"\n\nYour previous answer was rejected ({problem}). Answer again with only FILE: "
                       "sections that contain complete, valid pytest files.")
        return []

    def _repair(self, request: str, sources: list[Path], tests: list[Path],
                result: PytestResult, round_no: int, allow_tests: bool) -> list[Path]:
        budget = self.cfg.tdd_context_chars
        prompt = REPAIR_PROMPT.substitute(
            request=request, round=round_no, max_rounds=self.cfg.tdd_rounds,
            test_policy=TESTS_UNLOCKED if allow_tests else TESTS_LOCKED,
            output=clip_text(result.output, 5000),
            sources=self._render_files(sources, budget * 6 // 10),
            tests=self._render_files(tests, budget * 4 // 10),
        )
        text = self.llm.generate(prompt, force_cloud=True, slow=False)
        self.execute_bash(text)
        edited = self.apply_code_edits(
            text, accept=lambda p: not self._is_test_path(p), legacy=False, overwrite_fallback=True,
        )
        if allow_tests:
            written, problem = self._write_test_files(text, tests, lenient=False)
            if problem and not written:
                log.debug("[TDD] No test edits applied: %s", problem)
            edited += written
        return edited

    def run_tdd_loop(self, request: str, changed: list[Path]) -> TddReport:
        sources = self._tdd_sources(changed)
        if not sources:
            log.info("🧪 [TDD] No Python source changes to test; skipping.")
            return TddReport("skipped", "no Python source files changed")
        if not self._ensure_pytest():
            log.error("🛑 [TDD] pytest is not available (pip install pytest, or set FABLE_TDD=0).")
            return TddReport("unavailable", "pytest is not available")

        targets = [self._test_target(s) for s in sources]
        tests = self._generate_tests(request, sources, targets)
        if not tests:
            log.error("🛑 [TDD] Could not produce a valid test suite.")
            return TddReport("failed", "could not generate a valid test suite")

        touched: list[Path] = list(tests)
        result = self._run_pytest(tests)
        repairs, last_sig = 0, None
        while not result.passed and repairs < self.cfg.tdd_rounds:
            sig = failure_signature(result.output)
            stuck = sig == last_sig
            last_sig = sig
            repairs += 1
            allow_tests = stuck or result.no_tests
            log.warning("❌ [TDD] %s. Self-healing round %d/%d%s", result.summary, repairs,
                        self.cfg.tdd_rounds, " (tests unlocked)" if allow_tests else "")
            try:
                edited = self._repair(request, sources, tests, result, repairs, allow_tests)
            except Exception as e:
                log.error("❌ [TDD] Repair step failed: %s", e)
                break
            touched += edited
            for p in edited:
                if p.suffix == ".py" and not self._is_test_path(p) and p not in sources:
                    sources.append(p)
            if edited:
                result = self._run_pytest(tests)
            else:
                log.warning("⚠️ [TDD] The model produced no usable edits.")

        files = list(dict.fromkeys(touched))
        if result.passed:
            log.info("✅ [TDD] Green: %s (%d repair round%s).", result.summary, repairs, "" if repairs == 1 else "s")
            return TddReport("passed", result.summary, repairs, files)
        log.error("🛑 [TDD] Still failing after %d repair round%s: %s\n%s", repairs,
                  "" if repairs == 1 else "s", result.summary, clip_text(result.output, 2000))
        return TddReport("failed", result.summary, repairs, files)

    # ---- Main entry point ------------------------------------------------- #
    def resolve_error(self, user_input: str) -> bool:
        log.info("\n🚨 [Engine] Initializing Universal Agentic Engine...")
        prompt = PROMPT_TEMPLATE.substitute(request=user_input)

        try:
            response_text = self.llm.generate(prompt)
        except Exception as e:
            log.error("❌ [Cloud API] Error: %s", e)
            return False

        bash_ok = self.execute_bash(response_text)
        changed = self.apply_code_edits(response_text)

        files = list(changed)
        report: Optional[TddReport] = None
        if self.cfg.tdd:
            report = self.run_tdd_loop(user_input, changed)
            files += report.files
        self.last_tdd_report = report

        green = report is None or report.ok
        if self.cfg.auto_commit and files:
            if green:
                note = f" [tests: {report.summary}]" if report and report.status == "passed" else ""
                self._git_commit(files, f"Fable Auto-Commit: Task completed{note}")
            elif self.cfg.tdd_commit_on_fail:
                self._git_commit(files, f"Fable Auto-Commit: WIP, tests failing [{report.summary}]")
            else:
                log.warning("📝 [Git] Not committing: the tests did not pass. Review the changes, "
                            "or set FABLE_TDD_COMMIT_ON_FAIL=1 to commit anyway.")
        return bash_ok and green


def main(argv: Optional[list[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Fable self-healing engine")
    parser.add_argument("request", nargs="*", help="what to build or fix")
    parser.add_argument("--no-tdd", action="store_true", help="skip the test-driven loop")
    parser.add_argument("--rounds", type=int, help="max self-healing rounds (default 3)")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args(argv)

    logging.basicConfig(level=logging.DEBUG if args.verbose else logging.INFO, format="%(message)s")
    overrides = {}
    if args.no_tdd:
        overrides["tdd"] = False
    if args.rounds is not None:
        overrides["tdd_rounds"] = max(0, args.rounds)
    cfg = replace(Config(), **overrides)

    request = " ".join(args.request) or input("What should Fable build or fix? ")
    return 0 if SelfHealingEngine(cfg).resolve_error(request) else 1


if __name__ == "__main__":
    sys.exit(main())
